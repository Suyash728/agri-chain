"""
app/services/evaluation.py
--------------------------
Phase 11 — AI Trust Layer Evaluation & Performance Measurement service.

WHAT THIS MODULE DOES
----------------------
1. Benchmarks the real, complete AI Trust Layer pipeline (Phases 1–10) using
   controlled synthetic normal sequences and all 7 fault injection categories
   from Phase 9.
2. Does NOT create an alternative ML detector or bypass the verdict engine.
3. Derives ground truth strictly from simulator configuration and predictions
   strictly from pipeline verdicts:
     - verdict == "VALID"                 -> Predicted Normal
     - verdict == "ANOMALOUS"             -> Predicted Anomalous
     - verdict == "INSUFFICIENT_EVIDENCE" -> Separately reported, not forced into binary classes
4. Calculates standard metrics: TP, TN, FP, FN, Precision, Recall, F1, False Positive Rate.
5. Measures real pipeline latency per reading in milliseconds using high-precision timers.
6. Generates fault-wise breakdown across all evaluated scenarios.
7. Produces publication-quality visualizations using matplotlib/seaborn.
8. Clearly documents scientific caveats, simulation limitations, and real-world boundaries.
"""

from datetime import datetime, timezone
import json
import os
import time
from typing import Any, Dict, List, Optional, Tuple

import matplotlib
matplotlib.use("Agg")  # Non-interactive backend for headless execution
import matplotlib.pyplot as plt
import numpy as np

from app.schemas.evaluation import (
    ConfusionMatrix,
    EvaluationConfig,
    EvaluationMetrics,
    EvaluationReport,
    FaultWiseResult,
)
from app.schemas.simulation import FaultConfig, FaultType, SimulationConfig
from app.services.anomaly_detector import anomaly_detector
from app.services.audit import audit_service
from app.services.features import extract_features
from app.services.history import history_repository
from app.services.integrity import replay_repository
from app.services.simulator import telemetry_simulator


SCIENTIFIC_NOTES = (
    "SCIENTIFIC CAVEATS & EVALUATION SCOPE:\n"
    "1. Benchmark environment: Evaluated on synthetic, controlled IoT telemetry streams "
    "generated by the Phase 9 simulator.\n"
    "2. Scope distinction: Detection rates reflect performance against simulated fault models "
    "(thermal rate spikes, humidity leaps, Haversine displacement jumps, chronological regressions, "
    "exact SHA-256 replays, and telemetry gaps). They do NOT represent empirical field guarantees "
    "for real-world agricultural IoT sensors.\n"
    "3. ML state: Isolation Forest uses development hyperparameters (contamination=0.05, n_estimators=100) "
    "fitted to synthetic normal route baselines.\n"
    "4. Execution state: Evaluated using in-memory development repositories without persistent database latency.\n"
    "5. Boundary guarantees: Only VALID + READY_FOR_ORACLE events are eligible for Phase 10 downstream "
    "Oracle handoff. Anomalous records remain quarantined off-chain."
)


class EvaluationService:
    """
    Evaluates the complete AI Trust Layer pipeline across normal and faulty telemetry scenarios.
    """

    def run_pipeline_evaluation(
        self,
        config: Optional[EvaluationConfig] = None,
        output_dir: Optional[str] = "reports/figures",
    ) -> EvaluationReport:
        """
        Execute an end-to-end evaluation run against the real AI Trust Layer pipeline.

        Parameters
        ----------
        config : Optional[EvaluationConfig]
            Evaluation parameters. Uses defaults if None.
        output_dir : Optional[str]
            Directory path to save generated chart figures.

        Returns
        -------
        EvaluationReport
            Comprehensive metrics, fault breakdown, confusion matrix, and notes.
        """
        cfg = config or EvaluationConfig()
        from app.routers.telemetry import ingest_telemetry

        # Step 1: Clean repositories and optionally train the ML baseline
        history_repository.clear()
        replay_repository.clear()
        audit_service.clear()
        anomaly_detector.clear_model()

        if cfg.train_baseline_model:
            self._fit_baseline_model(cfg.random_seed)

        # Step 2: Build trial test scenarios
        # List of (scenario_name, is_fault, FaultConfig or None)
        scenarios: List[Tuple[str, bool, Optional[FaultConfig]]] = [("NORMAL", False, None)]
        for ft in cfg.fault_types:
            scenarios.append((ft.value, True, FaultConfig(fault_type=ft, position=cfg.sequence_length - 1)))

        latencies_ms: List[float] = []

        # Tracking variables
        tp = 0  # Faulty detected as ANOMALOUS
        tn = 0  # Normal accepted as VALID
        fp = 0  # Normal flagged as ANOMALOUS
        fn = 0  # Faulty accepted as VALID
        insufficient_count = 0

        fault_breakdowns: Dict[str, Dict[str, int]] = {
            s[0]: {"total": 0, "anomalous": 0, "valid": 0, "insufficient": 0} for s in scenarios
        }

        total_normal = 0
        total_faulty = 0

        # Step 3: Run trial sequences through the pipeline
        trial_seed = cfg.random_seed

        for scenario_name, is_fault, fault_cfg in scenarios:
            for trial_idx in range(cfg.sequences_per_fault):
                trial_seed += 1
                faults = [fault_cfg] if fault_cfg is not None else []

                sim_cfg = SimulationConfig(
                    device_id=f"DEV-EVAL-{scenario_name[:6]}-{trial_idx}",
                    batch_id=f"BATCH-EVAL-{scenario_name[:6]}",
                    num_readings=cfg.sequence_length,
                    random_seed=trial_seed,
                    faults=faults,
                )
                sequence = telemetry_simulator.generate_sequence(sim_cfg)

                # Clear history for this specific sequence trial so state is clean
                history_repository.clear()
                replay_repository.clear()

                last_resp: Optional[Dict[str, Any]] = None

                for reading in sequence:
                    t0 = time.perf_counter()
                    try:
                        resp = ingest_telemetry(reading)
                        elapsed_ms = (time.perf_counter() - t0) * 1000.0
                        latencies_ms.append(elapsed_ms)
                        last_resp = resp
                    except Exception as e:
                        elapsed_ms = (time.perf_counter() - t0) * 1000.0
                        latencies_ms.append(elapsed_ms)
                        # Phase 2 basic validation failure is by definition ANOMALOUS
                        last_resp = {"verdict": {"verdict": "ANOMALOUS"}}

                verdict_str = (
                    last_resp.get("verdict", {}).get("verdict", "INSUFFICIENT_EVIDENCE")
                    if last_resp
                    else "INSUFFICIENT_EVIDENCE"
                )

                # Update stats
                fault_breakdowns[scenario_name]["total"] += 1
                if is_fault:
                    total_faulty += 1
                else:
                    total_normal += 1

                if verdict_str == "ANOMALOUS":
                    fault_breakdowns[scenario_name]["anomalous"] += 1
                    if is_fault:
                        tp += 1
                    else:
                        fp += 1
                elif verdict_str == "VALID":
                    fault_breakdowns[scenario_name]["valid"] += 1
                    if is_fault:
                        fn += 1
                    else:
                        tn += 1
                else:
                    fault_breakdowns[scenario_name]["insufficient"] += 1
                    insufficient_count += 1

        total_cases = total_normal + total_faulty

        # Step 4: Calculate performance metrics safely
        precision = (tp / (tp + fp)) if (tp + fp) > 0 else 0.0
        recall = (tp / (tp + fn)) if (tp + fn) > 0 else 0.0
        f1_score = (2.0 * precision * recall / (precision + recall)) if (precision + recall) > 0 else 0.0
        fpr = (fp / (fp + tn)) if (fp + tn) > 0 else 0.0
        insufficient_rate = (insufficient_count / total_cases) if total_cases > 0 else 0.0
        mean_latency = float(np.mean(latencies_ms)) if latencies_ms else None

        metrics = EvaluationMetrics(
            total_cases=total_cases,
            total_normal_cases=total_normal,
            total_faulty_cases=total_faulty,
            tp=tp,
            tn=tn,
            fp=fp,
            fn=fn,
            precision=round(precision, 4),
            recall=round(recall, 4),
            f1_score=round(f1_score, 4),
            false_positive_rate=round(fpr, 4),
            insufficient_evidence_count=insufficient_count,
            insufficient_evidence_rate=round(insufficient_rate, 4),
            mean_latency_ms=round(mean_latency, 3) if mean_latency is not None else None,
        )

        conf_matrix = ConfusionMatrix(
            tp=tp,
            tn=tn,
            fp=fp,
            fn=fn,
            insufficient_evidence=insufficient_count,
            matrix=[[tn, fp], [fn, tp]],
        )

        # Step 5: Format Fault-wise Breakdown
        fault_results: List[FaultWiseResult] = []
        for name, data in fault_breakdowns.items():
            tot = data["total"]
            if name == "NORMAL":
                det_rate = (data["valid"] / tot) if tot > 0 else 0.0
            else:
                det_rate = (data["anomalous"] / tot) if tot > 0 else 0.0

            fault_results.append(
                FaultWiseResult(
                    fault_type=name,
                    total_cases=tot,
                    detected_anomalous=data["anomalous"],
                    accepted_valid=data["valid"],
                    insufficient_evidence=data["insufficient"],
                    detection_rate=round(det_rate, 4),
                )
            )

        report = EvaluationReport(
            config=cfg,
            metrics=metrics,
            confusion_matrix=conf_matrix,
            fault_wise_results=fault_results,
            generated_figures=[],
            scientific_notes=SCIENTIFIC_NOTES,
        )

        # Step 6: Generate visualizations if requested
        if output_dir:
            generated_paths = self.generate_evaluation_visualizations(report, output_dir)
            report.generated_figures = generated_paths

        return report

    def _fit_baseline_model(self, seed: int) -> None:
        """Fit Isolation Forest on synthetic normal route baseline readings."""
        cfg = SimulationConfig(num_readings=40, random_seed=seed, time_step_seconds=60.0)
        baseline = telemetry_simulator.generate_normal_sequence(cfg)

        vectors: List[List[float]] = []
        for i in range(1, len(baseline)):
            feats = extract_features(current=baseline[i], previous=baseline[i - 1])
            vectors.append(feats.to_feature_vector())

        anomaly_detector.fit(vectors)

    def generate_evaluation_visualizations(
        self,
        report: EvaluationReport,
        output_dir: str = "reports/figures",
    ) -> List[str]:
        """
        Generate visualization charts for evaluation report.

        Outputs:
          1. confusion_matrix.png
          2. fault_detection_rates.png
          3. metrics_summary.png
          4. verdict_distribution.png
        """
        os.makedirs(output_dir, exist_ok=True)
        saved_paths: List[str] = []

        # 1. Confusion Matrix Heatmap
        fig, ax = plt.subplots(figsize=(6, 5))
        cm_data = np.array(report.confusion_matrix.matrix)
        cax = ax.matshow(cm_data, cmap="Blues", alpha=0.85)
        for i in range(2):
            for j in range(2):
                ax.text(
                    j, i, str(cm_data[i, j]),
                    ha="center", va="center", fontsize=14, fontweight="bold",
                    color="black" if cm_data[i, j] < cm_data.max() / 2 else "white",
                )
        fig.colorbar(cax)
        ax.set_xticks([0, 1])
        ax.set_yticks([0, 1])
        ax.set_xticklabels(["Pred Normal", "Pred Anomalous"], fontsize=10)
        ax.set_yticklabels(["True Normal", "True Anomalous"], fontsize=10)
        ax.set_title("AI Trust Layer Confusion Matrix", pad=20, fontsize=12, fontweight="bold")
        plt.tight_layout()
        cm_path = os.path.join(output_dir, "confusion_matrix.png")
        plt.savefig(cm_path, dpi=200)
        plt.close(fig)
        saved_paths.append(cm_path)

        # 2. Detection Rate by Fault Type Bar Chart
        fig, ax = plt.subplots(figsize=(10, 5))
        labels = [fr.fault_type for fr in report.fault_wise_results]
        rates = [fr.detection_rate * 100.0 for fr in report.fault_wise_results]
        colors = ["#2b8a3e" if lbl == "NORMAL" else "#1c7ed6" for lbl in labels]

        bars = ax.bar(labels, rates, color=colors, width=0.6, edgecolor="#333333", linewidth=0.8)
        ax.set_ylabel("Detection Rate (%)", fontsize=11, fontweight="bold")
        ax.set_title("Detection Rate by Fault Category", fontsize=12, fontweight="bold", pad=12)
        ax.set_ylim(0, 115)
        ax.grid(axis="y", linestyle="--", alpha=0.6)
        plt.xticks(rotation=25, ha="right", fontsize=9)

        for bar in bars:
            height = bar.get_height()
            ax.annotate(
                f"{height:.1f}%",
                xy=(bar.get_x() + bar.get_width() / 2, height),
                xytext=(0, 3),
                textcoords="offset points",
                ha="center", va="bottom", fontsize=9, fontweight="bold",
            )
        plt.tight_layout()
        rates_path = os.path.join(output_dir, "fault_detection_rates.png")
        plt.savefig(rates_path, dpi=200)
        plt.close(fig)
        saved_paths.append(rates_path)

        # 3. Overall Metrics Summary
        fig, ax = plt.subplots(figsize=(8, 4.5))
        metric_names = ["Precision", "Recall", "F1-Score", "False Positive Rate"]
        m = report.metrics
        metric_values = [m.precision * 100.0, m.recall * 100.0, m.f1_score * 100.0, m.false_positive_rate * 100.0]
        palette = ["#228be6", "#40c057", "#fab005", "#fa5252"]

        mbars = ax.bar(metric_names, metric_values, color=palette, width=0.5, edgecolor="#333", linewidth=0.8)
        ax.set_ylabel("Score (%)", fontsize=11, fontweight="bold")
        ax.set_title("AI Trust Layer Classification Metrics", fontsize=12, fontweight="bold", pad=12)
        ax.set_ylim(0, 115)
        ax.grid(axis="y", linestyle="--", alpha=0.6)

        for bar in mbars:
            h = bar.get_height()
            ax.annotate(
                f"{h:.1f}%",
                xy=(bar.get_x() + bar.get_width() / 2, h),
                xytext=(0, 3),
                textcoords="offset points",
                ha="center", va="bottom", fontsize=10, fontweight="bold",
            )
        plt.tight_layout()
        metrics_path = os.path.join(output_dir, "metrics_summary.png")
        plt.savefig(metrics_path, dpi=200)
        plt.close(fig)
        saved_paths.append(metrics_path)

        # 4. Verdict Distribution Pie Chart
        fig, ax = plt.subplots(figsize=(6, 5))
        v_labels = ["VALID (True Negative)", "ANOMALOUS (True Positive)", "False Alarm (FP)", "Missed (FN)"]
        v_counts = [m.tn, m.tp, m.fp, m.fn]
        # Filter out 0 slices for clean pie
        filtered = [(l, c) for l, c in zip(v_labels, v_counts) if c > 0]
        if filtered:
            labels_f, counts_f = zip(*filtered)
            ax.pie(counts_f, labels=labels_f, autopct="%1.1f%%", startangle=140, colors=["#51cf66", "#339af0", "#ff6b6b", "#ffa94d"])
        ax.set_title("Verdict Decision Distribution", fontsize=12, fontweight="bold")
        plt.tight_layout()
        dist_path = os.path.join(output_dir, "verdict_distribution.png")
        plt.savefig(dist_path, dpi=200)
        plt.close(fig)
        saved_paths.append(dist_path)

        # 5. Export Markdown & JSON Summary Tables
        md_lines = [
            "# AgriChain AI Trust Layer — Benchmark Evaluation Report",
            "",
            "## Overall Classification Metrics",
            "| Metric | Value |",
            "| :--- | :--- |",
            f"| Total Cases | {m.total_cases} |",
            f"| True Positives (TP) | {m.tp} |",
            f"| True Negatives (TN) | {m.tn} |",
            f"| False Positives (FP) | {m.fp} |",
            f"| False Negatives (FN) | {m.fn} |",
            f"| **Precision** | **{m.precision:.4f}** ({m.precision * 100:.1f}%) |",
            f"| **Recall** | **{m.recall:.4f}** ({m.recall * 100:.1f}%) |",
            f"| **F1-Score** | **{m.f1_score:.4f}** ({m.f1_score * 100:.1f}%) |",
            f"| **False Positive Rate (FPR)** | **{m.false_positive_rate:.4f}** ({m.false_positive_rate * 100:.1f}%) |",
            f"| Mean Pipeline Latency | {m.mean_latency_ms:.2f} ms |" if m.mean_latency_ms is not None else "| Mean Pipeline Latency | N/A |",
            "",
            "## Fault-Wise Detection Breakdown",
            "| Fault Category | Total Trials | Detected Anomalous | Accepted Valid | Insufficient | Detection Rate (%) |",
            "| :--- | :--- | :--- | :--- | :--- | :--- |",
        ]
        for fr in report.fault_wise_results:
            md_lines.append(
                f"| {fr.fault_type} | {fr.total_cases} | {fr.detected_anomalous} | {fr.accepted_valid} | {fr.insufficient_evidence} | {fr.detection_rate * 100.0:.1f}% |"
            )

        md_lines.extend([
            "",
            "## Confusion Matrix",
            "| | Predicted Normal | Predicted Anomalous |",
            "| :--- | :--- | :--- |",
            f"| **Actual Normal** | {report.confusion_matrix.tn} (TN) | {report.confusion_matrix.fp} (FP) |",
            f"| **Actual Anomalous** | {report.confusion_matrix.fn} (FN) | {report.confusion_matrix.tp} (TP) |",
            "",
            "## Publication-Ready Figures",
            "- `confusion_matrix.png`",
            "- `fault_detection_rates.png`",
            "- `metrics_summary.png`",
            "- `verdict_distribution.png`",
            "",
            "## Scientific Notes & Evaluation Scope",
            report.scientific_notes,
        ])
        md_content = "\n".join(md_lines) + "\n"

        md_path = os.path.join(output_dir, "benchmark_summary.md")
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)

        json_path = os.path.join(output_dir, "benchmark_summary.json")
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(report.model_dump(mode="json"), f, indent=2)

        return saved_paths


# Singleton evaluation service instance
evaluation_service = EvaluationService()
